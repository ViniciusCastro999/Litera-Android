/**
 * Litera's icon set, matching the Phosphor Icons used in the LiteraUX Figma
 * Style Guide (file HjDOMSiT5S17DZKR77b8SY, "Ícones" section). Each glyph's
 * path data below is the exact SVG path exported from that Figma file (not
 * hand-approximated), parsed at build time via [PathParser] into a Compose
 * [ImageVector]. Each icon keeps its own source viewBox as the vector's
 * viewport so the coordinates can be pasted verbatim without renormalizing.
 *
 * The design system's Maven/JitPack distribution
 * (br.com.devsrsouza.compose.icons:phosphor) isn't reliably resolvable from
 * this build environment (not published to Maven Central, and its JitPack
 * build is currently broken), so rather than risk the whole project failing
 * to sync, these icons are embedded directly instead of pulled from that
 * library. If it becomes resolvable for you, this file can be deleted and
 * `PhosphorIcons.House` etc. swapped for the library's `Phosphor.House`.
 */
