    private fun buildIcon(
        name: String,
        viewportWidth: Float = 24f,
        viewportHeight: Float = 24f,
        block: androidx.compose.ui.graphics.vector.ImageVector.Builder.() -> Unit
    ): ImageVector = ImageVector.Builder(
        name = name,
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = viewportWidth,
        viewportHeight = viewportHeight
    ).apply(block).build()

    /** Adds an exact SVG path (as exported from Figma) as a solid fill. */
    private fun androidx.compose.ui.graphics.vector.ImageVector.Builder.fillPath(svgPathData: String) {
        addPath(
            pathData = PathParser().parsePathString(svgPathData).toNodes(),
            fill = SolidColor(Color.Black),
            pathFillType = PathFillType.NonZero
        )
    }

